# Generate the portfolio summary directly from the computed R results.
result <- readRDS("outputs/results/analysis.rds")
number <- function(x, digits = 2L) formatC(x, format = "f", digits = digits,
                                          decimal.mark = ",", big.mark = " ")
summary_rows <- result$best |>
  dplyr::select(Travel, Model, MASE) |>
  dplyr::left_join(result$impact |> dplyr::filter(Months == 12L) |>
                     dplyr::select(Travel, FirstYear = GapPct), by = "Travel") |>
  dplyr::left_join(result$impact |> dplyr::filter(Months == 32L) |>
                     dplyr::select(Travel, FullPeriod = GapPct), by = "Travel") |>
  dplyr::arrange(match(Travel, c("Air", "Rail", "Car")))
table_rows <- vapply(seq_len(nrow(summary_rows)), function(i) {
  row <- summary_rows[i, ]
  sprintf("| %s | %s | %s | %s%% | %s%% |", row$Travel, row$Model,
          number(row$MASE, 3L), number(row$FirstYear), number(row$FullPeriod))
}, character(1))
